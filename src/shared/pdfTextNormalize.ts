/** 归一：NFKC（江区部首/全角等）→ 部首补充区对照 → 去全部空白 */
export function normalizePdfText(text: string): string {
  return text
    .normalize('NFKC')
    .replace(/[\u2E80-\u2EFF]/g, (ch) => PDF_RADICAL_FIX[ch] ?? ch)
    .replace(/\s+/g, '')
}
