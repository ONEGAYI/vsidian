import type { MessageKey } from './locales/en'

/** 条目所属域：content = 正文域（本票逐项核实）；chrome = 界面域（#133 逐项核实） */
export type StyleContractDomain = 'content' | 'chrome'

/** 条目种类 */
export type StyleContractKind = 'container' | 'selector' | 'variable' | 'limitation'

/** Obsidian 兼容支持等级（诚实边界：语义对应 ≠ 原名可直接使用） */
export type ObsidianSupportLevel = 'direct' | 'semantic' | 'native' | 'none'

export interface StyleContractObsidian {
  /** Obsidian 对应选择器/变量（描述性，可含方向说明；无对应时说明本项目形态） */
  counterpart: string
  support: ObsidianSupportLevel
}

/** 类目定义（#145）：清单条目的二级分组（域内小类），分栏/分页与契约
 * JSON 共用的分组单一事实源。归类按条目实际语义，limitation 条目归入
 * 其所属域的限制类目。 */
export interface StyleContractCategory {
  /** kebab-case 类目 id（契约 JSON 消费方按 id 引用，一经公开不再变更） */
  id: string
  domain: StyleContractDomain
  /** 类目中文显示名（文档数据：HTML 指南与契约 JSON 直接使用；设置页 UI
   *  经 titleKey 取词——zh-cn 词条须与 title 一致，契约测试钉住） */
  title: string
  /** 设置页类目名称的消息键 */
  titleKey: MessageKey
  /** 域内呈现顺序（1 起，域内连续） */
  order: number
}

export interface StyleContractEntry {
  /** 稳定 ID（kebab-case；一经公开不再变更，弃用/移除条目保留 ID） */
  id: string
  domain: StyleContractDomain
  /** 所属类目 id（STYLE_CONTRACT_CATEGORIES 定义表；域须与条目一致） */
  category: string
  kind: StyleContractKind
  /** 选择器或变量名（族用 {1..6} 形态注记；limitation 为不支持项的名称） */
  target: string
  /** 用途 */
  purpose: string
  /** 适用视图 */
  views: readonly ('live' | 'reading')[]
  /** 状态说明（动态态触发条件；常驻入口可省略） */
  states?: string
  /** 必要 DOM 关系（命中该入口所需的结构前提） */
  dom: string
  /** 片段作者可直接使用的示例 CSS */
  example: string
  obsidian: StyleContractObsidian
  /** direct 级别名桥实际承接的 Obsidian 原名（与 DOM/变量别名常量同源，
   *  由契约测试钉住一致；族形态如 cm-header-{1..6}） */
  aliasTargets?: readonly string[]
  /** 验证定位（测试用例 / 探针字段 / CSS 契约测试） */
  verification: readonly string[]
  /** 引入记录（工单号） */
  introduced: string
  /** 弃用声明（版本 + 替代写法；技能 style-contract 弃用流程） */
  deprecated?: string
  /** 移除记录（版本 + 原因；须满足弃用期限） */
  removed?: string
  /** 界面域待逐项核实标记（#133 已全部核实移除；字段保留供未来新增域的
   *  迁移场景复用，携带条目会被契约测试拦截——不得自称已核实） */
  pendingVerification?: '#133'
}

