// @vitest-environment jsdom
import { afterEach, describe, expect, it, vi } from 'vitest'
import { ToastChannel, TOAST_ACTION_DURATION_MS } from '../../src/webview/toast'

afterEach(() => { vi.useRealTimers(); document.body.replaceChildren() })
describe('独立轻提示通道', () => {
  it('按粘贴组替换并清除过期反馈，不清除其他warning和等待消息', () => {
    vi.useFakeTimers()
    const app = document.createElement('div'); document.body.append(app)
    const toast = new ToastChannel(app)
    toast.show('图片提醒', 'warning')
    toast.show('保留格式', 'neutral', 'paste:1')
    toast.show('撤格式，再按一次', 'neutral', 'paste:1')
    toast.dismiss('paste:1')
    expect(app.querySelector('.vsidian-toast')?.textContent).toBe('图片提醒')
    vi.advanceTimersByTime(5000)
    expect(app.querySelector('.vsidian-toast')).toBeNull()
    toast.show('保留格式', 'neutral', 'paste:2')
    toast.show('撤格式，再按一次', 'neutral', 'paste:2')
    expect(app.querySelector('.vsidian-toast')?.textContent).toBe('撤格式，再按一次')
    toast.dismiss('paste:2'); vi.runAllTimers()
    expect(app.querySelector('.vsidian-toast')).toBeNull()
    toast.dispose()
  })
  it('只显示一条，连续重复合并，顺序显示并保持焦点', () => {
    vi.useFakeTimers()
    const app = document.createElement('div')
    app.id = 'app'
    const input = document.createElement('input')
    app.append(input); document.body.append(app); input.focus()
    app.style.setProperty('--vsidian-toast-warning-duration', '100')
    app.style.setProperty('--vsidian-toast-duration', '100')
    const toast = new ToastChannel(app)
    toast.show('图片提示', 'warning'); toast.show('图片提示', 'warning'); toast.show('已完成')
    expect(app.querySelectorAll('.vsidian-toast')).toHaveLength(1)
    expect(app.querySelector('.vsidian-toast')?.textContent).toBe('图片提示')
    expect(app.querySelector('.vsidian-toast-container')?.getAttribute('aria-live')).toBe('polite')
    expect(document.activeElement).toBe(input)
    vi.advanceTimersByTime(220)
    expect(app.querySelector('.vsidian-toast')?.textContent).toBe('已完成')
    toast.dispose(); vi.runAllTimers()
    expect(app.querySelector('.vsidian-toast-container')).toBeNull()
  })
  it('待显示上限五条；释放后不再产生 DOM 或计时器', () => {
    vi.useFakeTimers()
    const app = document.createElement('div'); document.body.append(app)
    const toast = new ToastChannel(app)
    for (let i = 0; i < 20; i++) toast.show(String(i))
    toast.dispose(); toast.show('迟到')
    expect(app.children).toHaveLength(0)
    expect(vi.getTimerCount()).toBe(0)
  })
  it('action 按钮渲染为真实 button；点击触发回调并立即移除气泡', () => {
    vi.useFakeTimers()
    const app = document.createElement('div'); document.body.append(app)
    const toast = new ToastChannel(app)
    const onClick = vi.fn()
    toast.show('已清空查询', 'neutral', 'query:clear', { label: '撤销', onClick })
    const button = app.querySelector<HTMLButtonElement>('button.vsidian-toast-action')
    expect(button?.getAttribute('type')).toBe('button')
    expect(button?.textContent).toBe('撤销')
    button!.click()
    expect(onClick).toHaveBeenCalledTimes(1)
    expect(app.querySelector('.vsidian-toast')).toBeNull()
    expect(vi.getTimerCount()).toBe(0)
    toast.dispose()
  })
  it('带 action 的 toast 固定 8000ms 窗口，不受 CSS 变量时长影响', () => {
    vi.useFakeTimers()
    const app = document.createElement('div'); app.id = 'app'; document.body.append(app)
    app.style.setProperty('--vsidian-toast-duration', '100')
    const toast = new ToastChannel(app)
    toast.show('已清空查询', 'neutral', undefined, { label: '撤销', onClick: () => {} })
    vi.advanceTimersByTime(TOAST_ACTION_DURATION_MS - 1)
    expect(app.querySelector('.vsidian-toast')).not.toBeNull()
    vi.advanceTimersByTime(1)
    expect(app.querySelector('.vsidian-toast')?.classList.contains('vsidian-toast--leaving')).toBe(true)
    vi.advanceTimersByTime(200)
    expect(app.querySelector('.vsidian-toast')).toBeNull()
    toast.dispose()
  })
  it('所有 toast 都渲染顶部倒计时条，条动画时长与呈现时长一致', () => {
    vi.useFakeTimers()
    const app = document.createElement('div'); document.body.append(app)
    const toast = new ToastChannel(app)
    toast.show('纯文字提示', 'neutral', 'k')
    expect(app.querySelector('.vsidian-toast > .vsidian-toast-timer')).not.toBeNull()
    expect(app.querySelector<HTMLElement>('.vsidian-toast-timer')?.style.animationDuration).toBe('2600ms')
    toast.show('带操作提示', 'neutral', 'k', { label: '撤销', onClick: () => {} })
    expect(app.querySelector<HTMLElement>('.vsidian-toast-timer')?.style.animationDuration).toBe(`${TOAST_ACTION_DURATION_MS}ms`)
    toast.dispose()
  })
  it('悬停暂停倒计时，离开后从剩余时长恢复而非重置', () => {
    vi.useFakeTimers()
    const app = document.createElement('div'); document.body.append(app)
    const toast = new ToastChannel(app)
    toast.show('已清空查询', 'neutral', 'q', { label: '撤销', onClick: () => {} })
    const bubble = app.querySelector<HTMLElement>('.vsidian-toast')
    vi.advanceTimersByTime(3000)
    bubble!.dispatchEvent(new Event('pointerenter'))
    vi.advanceTimersByTime(10000)
    expect(app.querySelector('.vsidian-toast--leaving')).toBeNull()
    bubble!.dispatchEvent(new Event('pointerleave'))
    vi.advanceTimersByTime(TOAST_ACTION_DURATION_MS - 3000 - 1)
    expect(app.querySelector('.vsidian-toast')).not.toBeNull()
    vi.advanceTimersByTime(1)
    expect(app.querySelector('.vsidian-toast')?.classList.contains('vsidian-toast--leaving')).toBe(true)
    vi.advanceTimersByTime(200)
    expect(app.querySelector('.vsidian-toast')).toBeNull()
    toast.dispose()
  })
  it('聚焦气泡内控件同样暂停倒计时，移焦后从剩余时长恢复', () => {
    vi.useFakeTimers()
    const app = document.createElement('div'); document.body.append(app)
    const toast = new ToastChannel(app)
    toast.show('已清空查询', 'neutral', 'q', { label: '撤销', onClick: () => {} })
    const bubble = app.querySelector<HTMLElement>('.vsidian-toast')
    vi.advanceTimersByTime(2000)
    bubble!.dispatchEvent(new FocusEvent('focusin'))
    vi.advanceTimersByTime(20000)
    expect(app.querySelector('.vsidian-toast--leaving')).toBeNull()
    bubble!.dispatchEvent(new FocusEvent('focusout'))
    vi.advanceTimersByTime(TOAST_ACTION_DURATION_MS - 2000 - 1)
    expect(app.querySelector('.vsidian-toast')).not.toBeNull()
    vi.advanceTimersByTime(1)
    expect(app.querySelector('.vsidian-toast')?.classList.contains('vsidian-toast--leaving')).toBe(true)
    toast.dispose()
  })
})
